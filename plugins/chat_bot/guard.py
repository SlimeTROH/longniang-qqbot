"""反注入（prompt injection）防护。

只做两件事：
1. 识别可疑输入，打日志（不阻断——阻断会误伤正常聊天）
2. 给系统提示词提供一段「安全规则」，让模型自己守住

真正的防线是提示词，不是正则。正则是用来事后排查的。
"""
from __future__ import annotations

import re

# 常见注入模式。命中只记日志，不拦截。
PATTERNS: list[tuple[str, str]] = [
    # 要求忽略之前的指令
    (r"(忽略|无视|忘记|抛开|不要管)[^。\n]{0,6}(之前|上面|以上|前面|先前)[^。\n]{0,6}(指令|规则|提示|设定|话)",
     "要求忽略前置指令"),
    (r"(ignore|disregard|forget)\s+(all\s+)?(previous|above|prior)\s+(instructions?|prompts?|rules?)",
     "要求忽略前置指令(en)"),
    # 角色切换
    (r"(从现在开始|从现在起|接下来)[^。\n]{0,8}(你是|你要扮演|你变成|你改叫)",
     "要求切换角色"),
    (r"(你|现在)(是|扮演|变成|当作)\s*(一个|另一个|新的)?\s*(AI|助手|机器人|猫娘|女仆|系统)",
     "要求切换角色"),
    (r"you\s+are\s+now\s+(a|an|the)\s+\w+",
     "要求切换角色(en)"),
    # 索要提示词（动作在前）
    (r"(输出|显示|告诉|重复|复述|打印|念出|发|分享|泄露|贴出|公开)"
     r"[^。\n]{0,8}(你的)?(系统)?(提示词|设定|prompt|指令|规则|人设|人格)",
     "索要系统提示词"),
    # 索要提示词（东西在前，比如「把你的提示词发给我」）
    (r"(提示词|prompt|系统提示|系统设定|人设)"
     r"[^。\n]{0,10}(发|给|分享|泄露|贴|输出|显示|重复|复述)",
     "索要系统提示词"),
    (r"(system|developer)\s+(prompt|message)",
     "索要系统提示词(en)"),
    (r"(repeat|print|show|reveal)\s+(your\s+)?(system\s+)?(prompt|instructions?)",
     "索要系统提示词(en)"),
    # 越狱话术
    (r"(jailbreak|越狱|DAN\s*模式|开发者模式|god\s*mode|无限制模式)",
     "越狱话术"),
    (r"(进入|开启|激活)[^。\n]{0,6}(开发者|god|无限制|管理员)\s*模式",
     "越狱话术"),
    # 要求执行动作
    (r"(执行|运行|调用)[^。\n]{0,6}(命令|代码|脚本|shell|powershell|cmd)",
     "要求执行命令"),
    (r"(读取|打开|访问|查看)[^。\n]{0,6}(文件|目录|路径|C:|D:)",
     "要求访问文件"),
    # 伪造系统消息
    (r"<\s*/?\s*(system|assistant|user)\s*>",
     "伪造消息标签"),
    (r"\[/?INST\]|<<\s*SYS\s*>>",
     "伪造消息标签"),
]


def scan(text: str) -> list[str]:
    """扫一遍文本，返回命中的「可疑类型」列表（可能为空）。"""
    if not text:
        return []
    hits: list[str] = []
    for pat, label in PATTERNS:
        try:
            if re.search(pat, text, re.IGNORECASE):
                if label not in hits:
                    hits.append(label)
        except re.error:
            continue
    return hits


